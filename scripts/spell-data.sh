#!/usr/bin/env bash
# Generates addons/ForeverTooltip/Data/SpellCoefficients.lua from the Forever client's own spell data,
# as wago.tools publishes it (product wowf). Run it again after a game patch, with the new build:
#
#   scripts/spell-data.sh 1.60.1.71037
#
# Builds are listed at https://wago.tools/builds (product wowf). The tables used:
#   SpellEffect        base points, per-level growth, variance, SP and AP coefficients, tick period
#   SpellClassOptions  which spells are class spells (SpellClassSet > 0)
#   SpellLevels        the spell's level, and the levels its base points grow between
#   SpellMisc          school mask and duration index
#   SpellDuration      duration in milliseconds, for the number of ticks
# Columns are found by their header names, so a reordered table still reads right; a missing column
# stops the script.
set -euo pipefail
source "$(dirname "$0")/lib.sh"

[[ $# -eq 1 ]] || die "usage: scripts/spell-data.sh <build, e.g. 1.60.1.71037>"
BUILD="$1"
[[ "$BUILD" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]] || die "not a build: $BUILD"
OUT="$ADDONS_DIR/ForeverTooltip/Data/SpellCoefficients.lua"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

for table in SpellEffect SpellClassOptions SpellLevels SpellMisc SpellDuration; do
	echo "==> Fetching $table ($BUILD)"
	curl -fsSL -o "$TMP/$table.csv" "https://wago.tools/db2/$table/csv?build=$BUILD" ||
		die "could not download $table for build $BUILD"
	# The tables used are all numeric. A quoted field would mean a text column and break the split below.
	if grep -q '"' "$TMP/$table.csv"; then
		die "$table has quoted fields; this script splits on commas only"
	fi
done

# LC_ALL=C: some awks read and print decimals with the locale's comma, which would zero every coefficient.
LC_ALL=C awk -F, -v build="$BUILD" '
	# Reads the header of each table into col[table, name] = index.
	FNR == 1 {
		table = FILENAME
		sub(/.*\//, "", table)
		sub(/\.csv$/, "", table)
		for (i = 1; i <= NF; i++) {
			name = $i
			sub(/\r$/, "", name)
			col[table, name] = i
		}
		next
	}
	function get(name) {
		if (!((table, name) in col)) {
			print "error: " table " has no column " name > "/dev/stderr"
			failed = 1
			exit 1
		}
		value = $(col[table, name])
		sub(/\r$/, "", value)
		return value
	}
	# Numbers as Lua literals: at most four decimals, no trailing zeros.
	function num(v) {
		v = sprintf("%.4f", v)
		sub(/0+$/, "", v)
		sub(/\.$/, "", v)
		if (v == "-0") v = "0"
		return v
	}
	table == "SpellDuration" { duration[get("ID")] = get("Duration"); next }
	table == "SpellClassOptions" { if (get("SpellClassSet") + 0 > 0) classSpell[get("SpellID")] = 1; next }
	table == "SpellLevels" {
		if (get("DifficultyID") != 0) next
		id = get("SpellID")
		spellLevel[id] = get("SpellLevel"); baseLevel[id] = get("BaseLevel"); maxLevel[id] = get("MaxLevel")
		next
	}
	table == "SpellMisc" {
		if (get("DifficultyID") != 0) next
		id = get("SpellID")
		school[id] = get("SchoolMask"); durationIndex[id] = get("DurationIndex")
		next
	}
	table == "SpellEffect" {
		if (get("DifficultyID") != 0) next
		id = get("SpellID")
		effect = get("Effect") + 0; aura = get("EffectAura") + 0
		kind = ""; periodic = "false"
		if (effect == 2 || effect == 9) kind = "damage"
		else if (effect == 10) kind = "heal"
		else if (effect == 6 || effect == 35) {
			periodic = "true"
			if (aura == 3 || aura == 53) kind = "damage"
			else if (aura == 8) kind = "heal"
			else if (aura == 69) { kind = "absorb"; periodic = "false" }
		}
		if (kind == "") next
		n = ++effects[id]
		e[id, n, "index"] = get("EffectIndex"); e[id, n, "kind"] = kind; e[id, n, "periodic"] = periodic
		e[id, n, "base"] = get("EffectBasePointsF"); e[id, n, "perLevel"] = get("EffectRealPointsPerLevel")
		e[id, n, "variance"] = get("Variance"); e[id, n, "sp"] = get("EffectBonusCoefficient")
		e[id, n, "ap"] = get("BonusCoefficientFromAP"); e[id, n, "period"] = get("EffectAuraPeriod")
		next
	}
	END {
		if (failed) exit 1
		print "local _, ns = ..."
		print ""
		print "-- GENERATED by scripts/spell-data.sh " build ". Do not edit: run the script again."
		print "--"
		print "-- The Forever client'"'"'s own spell data for class spells with a damage, heal or absorb effect that"
		print "-- scales with spell power or attack power. Per spell: school mask, level, the levels its base"
		print "-- points grow between (maxLevel 0: no growth), duration in ms (0: none), and per effect: index,"
		print "-- kind, periodic, base points (per tick when periodic), growth per level, variance, coefficients"
		print "-- from spell power (sp, per tick when periodic) and attack power (ap), tick period in ms."
		print "-- sp is 0 for physical spells: the client gives them a placeholder coefficient of 1."
		print "ns.SpellCoefficientsBuild = \"" build "\""
		print ""
		print "-- One line per spell and per effect: StyLua would spread this over 20 times the lines."
		print "-- stylua: ignore"
		print "ns.SpellCoefficients = {"
		count = 0
		for (id in effects) ids[++count] = id + 0
		# Insertion sort by spell ID: a stable file keeps diffs between builds readable.
		for (i = 2; i <= count; i++) {
			v = ids[i]
			for (j = i - 1; j >= 1 && ids[j] > v; j--) ids[j + 1] = ids[j]
			ids[j + 1] = v
		}
		written = 0
		for (i = 1; i <= count; i++) {
			id = ids[i]
			if (!(id in classSpell)) continue
			physical = (school[id] + 0 == 1)
			scaled = 0
			for (n = 1; n <= effects[id]; n++) {
				if (physical) e[id, n, "sp"] = 0
				if (e[id, n, "sp"] + 0 > 0 || e[id, n, "ap"] + 0 > 0) scaled = 1
			}
			if (!scaled) continue
			ms = duration[durationIndex[id]] + 0
			if (ms < 0) ms = 0
			printf "\t[%d] = { school = %d, level = %d, baseLevel = %d, maxLevel = %d, duration = %d, effects = {\n", id, school[id], spellLevel[id], baseLevel[id], maxLevel[id], ms
			# Effects in EffectIndex order, whatever order the rows of the table come in.
			for (k = 1; k <= effects[id]; k++) order[k] = k
			for (k = 2; k <= effects[id]; k++) {
				v = order[k]
				for (j = k - 1; j >= 1 && e[id, order[j], "index"] + 0 > e[id, v, "index"] + 0; j--) order[j + 1] = order[j]
				order[j + 1] = v
			}
			for (k = 1; k <= effects[id]; k++) {
				n = order[k]
				printf "\t\t{ index = %d, kind = \"%s\", periodic = %s, base = %s, perLevel = %s, variance = %s, sp = %s, ap = %s, period = %d },\n", e[id, n, "index"], e[id, n, "kind"], e[id, n, "periodic"], num(e[id, n, "base"]), num(e[id, n, "perLevel"]), num(e[id, n, "variance"]), num(e[id, n, "sp"]), num(e[id, n, "ap"]), e[id, n, "period"]
			}
			print "\t} },"
			written++
		}
		print "}"
		print written " spells" > "/dev/stderr"
		# No spell at all means the tables came back empty or from another game: keep the old file.
		if (written == 0) exit 1
	}
' "$TMP/SpellDuration.csv" "$TMP/SpellClassOptions.csv" "$TMP/SpellLevels.csv" "$TMP/SpellMisc.csv" "$TMP/SpellEffect.csv" >"$TMP/out.lua"

mkdir -p "$(dirname "$OUT")"
mv "$TMP/out.lua" "$OUT"
echo "==> Wrote $OUT"
